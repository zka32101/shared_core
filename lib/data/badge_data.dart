/// 教科に応じてフィルタされたバッジリストを取得
List<BadgeModel> getBadgesForSubject(String? subject) {
  if (subject == null) return unifiedBadges;
  return unifiedBadges
      .where((badge) => badge.subjects == null || badge.subjects!.contains(subject))
      .toList();
}
